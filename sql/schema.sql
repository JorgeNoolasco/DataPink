CREATE TABLE public.professor (
    id_professor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_auth UUID UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
    nome_professor VARCHAR(100) NOT NULL,
    email_professor VARCHAR(255) NOT NULL UNIQUE,
    telefone_professor VARCHAR(11),
    especialidade_professor VARCHAR(100),
    tipo_acesso TEXT NOT NULL DEFAULT 'professor' CHECK (tipo_acesso IN ('professor', 'admin'))
);

CREATE TABLE public.curso (
    id_curso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_curso VARCHAR(100) NOT NULL UNIQUE,
    descricao_curso VARCHAR(255),
    cargahoraria_curso NUMERIC(10,2) NOT NULL CHECK (cargahoraria_curso > 0)
);

CREATE TABLE public.turma (
    id_turma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso BIGINT NOT NULL REFERENCES public.curso(id_curso) ON DELETE RESTRICT,
    id_professor BIGINT NOT NULL REFERENCES public.professor(id_professor) ON DELETE RESTRICT,
    ano_letivo INTEGER NOT NULL CHECK (ano_letivo BETWEEN 2000 AND 2100),
    semestre_turma SMALLINT NOT NULL CHECK (semestre_turma IN (1, 2)),
    turno_turma VARCHAR(20) NOT NULL CHECK (turno_turma IN ('Manhã', 'Tarde', 'Noite', 'Integral')),
    UNIQUE (id_curso, id_professor, ano_letivo, semestre_turma, turno_turma)
);

CREATE TABLE public.aluno (
    id_aluno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_aluno VARCHAR(100) NOT NULL,
    data_nascimento DATE NOT NULL CHECK (data_nascimento <= CURRENT_DATE),
    email_aluno VARCHAR(255) NOT NULL UNIQUE,
    telefone_aluno VARCHAR(11),
    criado_por UUID DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE public.matricula (
    id_matricula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno BIGINT NOT NULL REFERENCES public.aluno(id_aluno) ON DELETE CASCADE,
    id_turma BIGINT NOT NULL REFERENCES public.turma(id_turma) ON DELETE CASCADE,
    data_matricula DATE NOT NULL DEFAULT CURRENT_DATE,
    situacao_matricula VARCHAR(20) NOT NULL DEFAULT 'Ativa'
        CHECK (situacao_matricula IN ('Ativa', 'Concluída', 'Trancada', 'Cancelada')),
    UNIQUE (id_aluno, id_turma)
);

CREATE TABLE public.nota (
    id_nota BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_matricula BIGINT NOT NULL REFERENCES public.matricula(id_matricula) ON DELETE CASCADE,
    descricao_nota VARCHAR(100) NOT NULL,
    valor_nota NUMERIC(4,2) NOT NULL CHECK (valor_nota BETWEEN 0 AND 10),
    data_nota DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE INDEX matricula_turma_idx ON public.matricula(id_turma);
CREATE INDEX matricula_aluno_idx ON public.matricula(id_aluno);
CREATE INDEX nota_matricula_idx ON public.nota(id_matricula);
